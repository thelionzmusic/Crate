// Crate Additive's factory sounds, by kind. Organs are named by their registration, read as an
// organist writes it: nine digits, one per drawbar from 16' to 1'. The rest are the harmonic
// layer alone. Levels are balanced like Crate FM's (tests/web/instruments.js checks them).

// a registration as drawbar settings, only where it differs from the default 888000000
const reg = (r) => Object.fromEntries([...r].map((d, i) => [`db${i + 1}`, +d]).filter(([k, x]) => x !== (+k.slice(2) <= 3 ? 8 : 0)));
const organ = (r, extra = {}) => ({ ...reg(r), ...extra });
const SLOW = { rotary: true }, FAST = { rotary: true, fast: true };
const perc3 = { perc: 2 }, perc2 = { perc: 1 };
// the harmonic layer alone, with its own envelope
const harm = (extra) => ({ organ: 0, harm: 1, ...extra });
const pluck = (d, r = 0.3) => ({ aa: 0.002, ad: d, as: 0, ar: r });

